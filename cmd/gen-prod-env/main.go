// Command gen-prod-env prints a fresh .env for the production compose stack
// (compose.yaml): new PASETO keys and random shared secrets, never the example
// values from example.app.env.
//
// Usage (from the repo root, next to compose.yaml):
//
//	go run ./cmd/gen-prod-env -site cms.example.com > .env
//
// The output holds secrets: keep it out of git (.env is ignored) and store it in
// your secret manager or GitHub environment secrets. See docs/operations/deploy.md.
package main

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/hex"
	"flag"
	"fmt"
	"io"
	"log"
	"os"
)

func main() {
	site := flag.String("site", "localhost", "SITE_ADDRESS for Caddy: your domain (automatic HTTPS) or localhost")
	flag.Parse()

	if err := writeEnv(os.Stdout, rand.Reader, *site); err != nil {
		log.Fatal(err)
	}
}

// writeEnv writes the .env file, reading all key material and secrets from random.
func writeEnv(w io.Writer, random io.Reader, site string) error {
	pub, priv, err := ed25519.GenerateKey(random)
	if err != nil {
		return fmt.Errorf("generate ed25519 key: %w", err)
	}

	// Hex secrets are URL-safe, which POSTGRES_PASSWORD needs: compose builds the
	// API's DB_SOURCE URL from it without escaping.
	secret := func(n int) (string, error) {
		b := make([]byte, n)
		if _, err := io.ReadFull(random, b); err != nil {
			return "", fmt.Errorf("read random bytes: %w", err)
		}
		return hex.EncodeToString(b), nil
	}
	values := map[string]string{}
	for _, name := range []string{"PASETO_V4_LOCAL_KEY_HEX", "POSTGRES_PASSWORD", "ROLE_LOOKUP_SECRET", "COLLAB_INTERNAL_SECRET"} {
		if values[name], err = secret(32); err != nil {
			return err
		}
	}

	_, err = fmt.Fprintf(w, `# Generated by cmd/gen-prod-env. Secrets: never commit this file.
# Caddy's site address: a domain gets a Let's Encrypt certificate automatically
# (ports 80 and 443 must reach this host); localhost uses Caddy's local CA.
SITE_ADDRESS=%s

POSTGRES_PASSWORD=%s

# Ed25519 (access tokens + collab tickets) and XChaCha20 (refresh tokens) keys.
# The collab service verifies tickets with the same public key.
PASETO_V4_PUBLIC_KEY_HEX=%s
PASETO_V4_PRIVATE_KEY_HEX=%s
PASETO_V4_LOCAL_KEY_HEX=%s

# Shared between the api and collab services.
ROLE_LOOKUP_SECRET=%s
COLLAB_INTERNAL_SECRET=%s
`,
		site,
		values["POSTGRES_PASSWORD"],
		hex.EncodeToString(pub),
		hex.EncodeToString(priv),
		values["PASETO_V4_LOCAL_KEY_HEX"],
		values["ROLE_LOOKUP_SECRET"],
		values["COLLAB_INTERNAL_SECRET"],
	)
	return err
}
