// Command gen-plugins writes api/plugins_gen.go (#458, docs/design/plugin-system.md
// section 7.1): one blank import of each plugin's server package,
// web/plugins/<slug>/server, so its init() registers its hooks with pluginsdk when the
// API starts. Go has no runtime loading, so a plugin's hooks are compiled in; the file
// is committed, and CI runs --check so it can't fall behind web/plugins.
//
//	go run ./cmd/gen-plugins           # rewrite api/plugins_gen.go
//	go run ./cmd/gen-plugins --check   # exit 1 if it is out of date
//
// Run it from the repository root (or pass -root). A plugin has server code when its
// server/ directory holds a non-test .go file; symlinked plugin directories are skipped,
// as the startup scan skips them.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const (
	pluginsDir = "web/plugins"
	outputFile = "api/plugins_gen.go"
)

var slugRe = regexp.MustCompile(`^[a-z][a-z0-9-]{0,62}$`)

func main() {
	check := flag.Bool("check", false, "exit 1 if "+outputFile+" is out of date instead of writing it")
	root := flag.String("root", ".", "the repository root")
	flag.Parse()
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, "gen-plugins:", err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	generated, err := generate(root)
	if err != nil {
		return err
	}
	path := filepath.Join(root, filepath.FromSlash(outputFile))
	if check {
		current, err := os.ReadFile(path)
		if err != nil && !errors.Is(err, fs.ErrNotExist) {
			return err
		}
		if !bytes.Equal(current, generated) {
			return fmt.Errorf("%s is out of date: run go run ./cmd/gen-plugins and commit it", outputFile)
		}
		return nil
	}
	return os.WriteFile(path, generated, 0o644)
}

// generate returns api/plugins_gen.go for the plugins under root.
func generate(root string) ([]byte, error) {
	module, err := modulePath(filepath.Join(root, "go.mod"))
	if err != nil {
		return nil, err
	}
	slugs, err := serverPlugins(filepath.Join(root, filepath.FromSlash(pluginsDir)))
	if err != nil {
		return nil, err
	}

	var b strings.Builder
	b.WriteString("// Code generated by go run ./cmd/gen-plugins; DO NOT EDIT.\n\n")
	b.WriteString("// The server hooks of every plugin in web/plugins (#458): each import's init()\n")
	b.WriteString("// registers the plugin with pluginsdk, and the startup scan checks the hooks it\n")
	b.WriteString("// registers against its plugin.json.\n\n")
	b.WriteString("package api\n")
	if len(slugs) == 0 {
		b.WriteString("\n// No plugin in web/plugins has server code.\n")
	} else {
		b.WriteString("\nimport (\n")
		for _, slug := range slugs {
			fmt.Fprintf(&b, "\t_ %q\n", module+"/"+pluginsDir+"/"+slug+"/server")
		}
		b.WriteString(")\n")
	}
	return format.Source([]byte(b.String()))
}

// serverPlugins lists, sorted, the plugin directories under dir whose server/ holds a
// non-test .go file. No dir: none.
func serverPlugins(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var slugs []string
	for _, entry := range entries {
		if !entry.IsDir() || entry.Type()&fs.ModeSymlink != 0 {
			continue
		}
		slug := entry.Name()
		files, err := os.ReadDir(filepath.Join(dir, slug, "server"))
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			return nil, err
		}
		hasCode := false
		for _, file := range files {
			name := file.Name()
			if file.Type().IsRegular() && strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go") {
				hasCode = true
				break
			}
		}
		if !hasCode {
			continue
		}
		if !slugRe.MatchString(slug) {
			return nil, fmt.Errorf("%s/%s has server code but %q is not a plugin id", pluginsDir, slug, slug)
		}
		slugs = append(slugs, slug)
	}
	sort.Strings(slugs)
	return slugs, nil
}

// modulePath reads the module line of go.mod.
func modulePath(goMod string) (string, error) {
	raw, err := os.ReadFile(goMod)
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(raw), "\n") {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(line), "module "); ok {
			return strings.Trim(strings.TrimSpace(rest), `"`), nil
		}
	}
	return "", fmt.Errorf("%s has no module line", goMod)
}
