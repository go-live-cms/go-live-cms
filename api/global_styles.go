// Global styles (#485, docs/design/theme-builder.md section 6): a validated, partial
// override of the active theme's declared tokens, in ThemeConfig's nesting (6.2):
//
//	{"colors": {"light": {"primary": "#155e4b"}}, "typography": {"fontFamily": {"heading": "inter"}}}
//
// The values end up in a <style> element (core's web/src/lib/themeTokens.ts), so nothing
// free-form may reach it: every value matches the grammar of 6.3, and only keys the theme
// declares are accepted (an unknown one is refused, not dropped). The same rules are in
// web/src/lib/globalStyles.ts (the form), and web/src/lib/globalStyleVectors.json pins
// both (TestGlobalStyleVectors and the web's globalStyles.test.ts).

// The manifest the API reads the themes' declared tokens from: generated by the web build
// from each theme.config.ts (scripts/theme-blocks-manifest.mjs, `npm run themes:manifest`),
// because the API can't run TypeScript. Shipped with web/themes like blocks.manifest.json.
const themeTokenManifestPath = "web/themes/tokens.manifest.json"

// FontOption is one entry of a theme's `fontOptions` (6.1): an id an override stores, the
// label the styles screen shows and the CSS stack it emits.
type FontOption struct {
	ID    string `json:"id"`
	Label string `json:"label"`
	Stack string `json:"stack"`
}

// ThemeTokens is one theme's entry: whether its base layout merges global styles
// (`supports.globalStyles`), its declared tokens with their default values (ThemeConfig's
// token groups), and its font options.
type ThemeTokens struct {
	SupportsGlobalStyles bool           `json:"supports_global_styles"`
	Tokens               map[string]any `json:"tokens"`
	FontOptions          []FontOption   `json:"font_options"`
}

// ThemeTokenManifest is web/themes/tokens.manifest.json. The zero value knows no theme,
// so no theme supports global styles.
type ThemeTokenManifest struct {
	ManifestVersion int                    `json:"manifest_version"`
	Themes          map[string]ThemeTokens `json:"themes"`
}

var fontOptionIDRe = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,39}$`)

// LoadThemeTokenManifest reads the manifest. A missing file is not an error (no theme
// supports global styles; the caller logs it). A file that exists but can't be used is.
func LoadThemeTokenManifest(path string) (ThemeTokenManifest, bool, error) {
	raw, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return ThemeTokenManifest{}, false, nil
	}
	if err != nil {
		return ThemeTokenManifest{}, false, err
	}
	var manifest ThemeTokenManifest
	if err := json.Unmarshal(raw, &manifest); err != nil {
		return ThemeTokenManifest{}, true, fmt.Errorf("theme token manifest %s: %w", path, err)
	}
	if manifest.ManifestVersion != 1 {
		return ThemeTokenManifest{}, true, fmt.Errorf("theme token manifest %s: unsupported manifest_version %d", path, manifest.ManifestVersion)
	}
	for slug, theme := range manifest.Themes {
		for _, option := range theme.FontOptions {
			if !fontOptionIDRe.MatchString(option.ID) || option.Stack == "" {
				return ThemeTokenManifest{}, true, fmt.Errorf("theme token manifest %s: %s has a bad font option %q", path, slug, option.ID)
			}
		}
		if _, ok := theme.Tokens["colors"].(map[string]any); !ok {
			return ThemeTokenManifest{}, true, fmt.Errorf("theme token manifest %s: %s declares no colors", path, slug)
		}
	}
	return manifest, true, nil
}

// systemFontIDs are core's fixed system stacks (6.1), which any theme may offer besides
// its own fontOptions. The stacks themselves are in web/src/lib/globalStyles.ts.
var systemFontIDs = []string{"system-sans", "system-serif", "system-mono"}

// The error codes a refused override answers with.
const (
	globalStyleUnknownToken = "unknown_token" // a key the theme doesn't declare (or core can't style)
	globalStyleInvalidValue = "invalid_value" // a value outside the grammar, or the wrong JSON type
	globalStyleTokenOrder   = "token_order"   // contentWidth ≤ wideWidth ≤ container, spacing increasing
)

// globalStyleError is a refused override: the first offending path (dotted, keys walked in
// sorted order so both validators name the same one) and why.
type globalStyleError struct {
	Code    string
	Path    string
	Message string
}

// Error is the message both validators show: "colors.light.primary: must be a colour …".
func (e *globalStyleError) Error() string {
	if e.Path == "" {
		return e.Message
	}
	return e.Path + ": " + e.Message
}

// The value kinds of 6.3.
type styleKind int

const (
	styleGroup styleKind = iota
	styleColor
	styleLength
	styleLineHeight
	styleFont
)

// styleNode is the shape core can style: fixed children, or any declared key (`each`).
type styleNode struct {
	kind     styleKind
	children map[string]*styleNode
	each     *styleNode
}

var (
	colorNode      = &styleNode{kind: styleColor}
	lengthNode     = &styleNode{kind: styleLength}
	lineHeightNode = &styleNode{kind: styleLineHeight}
	fontNode       = &styleNode{kind: styleFont}
	paletteNode    = &styleNode{each: colorNode}
	blockPalette   = &styleNode{each: &styleNode{children: map[string]*styleNode{"text": colorNode, "background": colorNode}}}

	globalStyleSchema = &styleNode{children: map[string]*styleNode{
		"colors":      {children: map[string]*styleNode{"light": paletteNode, "dark": paletteNode}},
		"blockColors": {children: map[string]*styleNode{"light": blockPalette, "dark": blockPalette}},
		"typography": {children: map[string]*styleNode{
			"fontFamily": {each: fontNode},
			"fontSize":   {each: lengthNode},
			"lineHeight": {each: lineHeightNode},
		}},
		"layout":  {each: lengthNode},
		"spacing": {each: lengthNode},
		"radius":  {each: lengthNode},
	}}
)

// Grammar (6.3). Spaces only (never tabs or newlines) inside clamp().
const (
	lengthPattern = `(?:\d{1,5}(?:\.\d{1,4})?|\.\d{1,4})(?:px|rem|em|%|vw)`
	maxStyleValue = 100
	minLineHeight = 1.0
	maxLineHeight = 2.5
)

var (
	colorRe        = regexp.MustCompile(`^#[0-9a-fA-F]{6}$`)
	simpleLengthRe = regexp.MustCompile(`^(\d{1,5}(?:\.\d{1,4})?|\.\d{1,4})(px|rem|em|%|vw)$`)
	clampRe        = regexp.MustCompile(`^clamp\( *(` + lengthPattern + `) *, *(` + lengthPattern + `)(?: *\+ *(` + lengthPattern + `))? *, *(` + lengthPattern + `) *\)$`)
)

// normalizeColor is `#rrggbb`, lowercased.
func normalizeColor(value string) (string, bool) {
	if !colorRe.MatchString(value) {
		return "", false
	}
	return strings.ToLower(value), true
}

// normalizeLength is a length (`680px`, `1.5rem`) or `clamp(<length>, <length or sum>,
// <length>)` written with single spaces: `clamp(1rem, 1rem + 0.25vw, 1.2rem)`.
func normalizeLength(value string) (string, bool) {
	if len(value) > maxStyleValue {
		return "", false
	}
	if simpleLengthRe.MatchString(value) {
		return value, true
	}
	m := clampRe.FindStringSubmatch(value)
	if m == nil {
		return "", false
	}
	middle := m[2]
	if m[3] != "" {
		middle += " + " + m[3]
	}
	return "clamp(" + m[1] + ", " + middle + ", " + m[4] + ")", true
}

// simpleLength splits a plain length into its number and unit; ok is false for clamp().
func simpleLength(value string) (float64, string, bool) {
	m := simpleLengthRe.FindStringSubmatch(value)
	if m == nil {
		return 0, "", false
	}
	n, err := strconv.ParseFloat(m[1], 64)
	if err != nil {
		return 0, "", false
	}
	return n, m[2], true
}

// ValidateGlobalStyles checks an override against a theme's declared tokens and returns
// it normalized (colours lowercased, clamp() spaced, empty groups dropped). raw must be a
// JSON object.
func ValidateGlobalStyles(raw json.RawMessage, theme ThemeTokens) (map[string]any, *globalStyleError) {
	decoder := json.NewDecoder(bytes.NewReader(raw))
	decoder.UseNumber()
	var input any
	if err := decoder.Decode(&input); err != nil {
		return nil, &globalStyleError{Code: globalStyleInvalidValue, Message: "must be a JSON object"}
	}
	return validateGlobalStyleValue(input, theme)
}

func validateGlobalStyleValue(input any, theme ThemeTokens) (map[string]any, *globalStyleError) {
	object, ok := input.(map[string]any)
	if !ok {
		return nil, &globalStyleError{Code: globalStyleInvalidValue, Message: "must be a JSON object"}
	}
	fonts := map[string]bool{}
	for _, id := range systemFontIDs {
		fonts[id] = true
	}
	for _, option := range theme.FontOptions {
		fonts[option.ID] = true
	}
	normalized, err := walkGlobalStyles(object, globalStyleSchema, theme.Tokens, "", fonts)
	if err != nil {
		return nil, err
	}
	if err := checkTokenOrder(normalized, theme.Tokens); err != nil {
		return nil, err
	}
	return normalized, nil
}

func joinPath(path, key string) string {
	if path == "" {
		return key
	}
	return path + "." + key
}

func sortedStyleKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func walkGlobalStyles(input map[string]any, node *styleNode, declared map[string]any, path string, fonts map[string]bool) (map[string]any, *globalStyleError) {
	out := map[string]any{}
	for _, key := range sortedStyleKeys(input) {
		keyPath := joinPath(path, key)
		child := node.each
		if node.children != nil {
			child = node.children[key]
		}
		declaredValue, isDeclared := declared[key]
		if child == nil || !isDeclared || declaredValue == nil {
			return nil, &globalStyleError{Code: globalStyleUnknownToken, Path: keyPath, Message: "this theme doesn't declare this token"}
		}
		value := input[key]
		if child.kind == styleGroup {
			object, ok := value.(map[string]any)
			if !ok {
				return nil, &globalStyleError{Code: globalStyleInvalidValue, Path: keyPath, Message: "must be an object"}
			}
			declaredObject, ok := declaredValue.(map[string]any)
			if !ok {
				return nil, &globalStyleError{Code: globalStyleUnknownToken, Path: keyPath, Message: "this theme doesn't declare this token"}
			}
			nested, err := walkGlobalStyles(object, child, declaredObject, keyPath, fonts)
			if err != nil {
				return nil, err
			}
			if len(nested) > 0 {
				out[key] = nested
			}
			continue
		}
		if _, isGroup := declaredValue.(map[string]any); isGroup {
			return nil, &globalStyleError{Code: globalStyleUnknownToken, Path: keyPath, Message: "this theme doesn't declare this token"}
		}
		leaf, err := validateStyleLeaf(child.kind, value, keyPath, fonts)
		if err != nil {
			return nil, err
		}
		out[key] = leaf
	}
	return out, nil
}

func validateStyleLeaf(kind styleKind, value any, path string, fonts map[string]bool) (any, *globalStyleError) {
	invalid := func(message string) *globalStyleError {
		return &globalStyleError{Code: globalStyleInvalidValue, Path: path, Message: message}
	}
	if kind == styleLineHeight {
		number, ok := value.(json.Number)
		if !ok {
			return nil, invalid("must be a number")
		}
		f, err := number.Float64()
		if err != nil || math.IsNaN(f) || f < minLineHeight || f > maxLineHeight {
			return nil, invalid("must be a number from 1 to 2.5")
		}
		return f, nil
	}
	text, ok := value.(string)
	if !ok {
		return nil, invalid("must be a string")
	}
	switch kind {
	case styleColor:
		if color, ok := normalizeColor(text); ok {
			return color, nil
		}
		return nil, invalid("must be a colour like #1b7760")
	case styleLength:
		if length, ok := normalizeLength(text); ok {
			return length, nil
		}
		return nil, invalid("must be a length (px, rem, em, %, vw) or clamp() of lengths")
	case styleFont:
		if fonts[text] {
			return text, nil
		}
		return nil, invalid("must be one of the theme's font options or a system font")
	}
	return nil, invalid("unsupported value")
}

// mergedString is the override's value at group.key, else the theme's default.
func mergedString(override, declared map[string]any, key string) (string, bool) {
	if v, ok := override[key].(string); ok {
		return v, true
	}
	v, ok := declared[key].(string)
	return v, ok
}

// lengthAtMost: a ≤ b when both are plain lengths in the same unit; anything else (clamp,
// different units) can't be compared here and passes.
func lengthAtMost(a, b string) bool {
	an, au, aok := simpleLength(a)
	bn, bu, bok := simpleLength(b)
	if !aok || !bok || au != bu {
		return true
	}
	return an <= bn
}

// checkTokenOrder applies 6.1's rules to the override merged with the theme's defaults:
// contentWidth ≤ wideWidth ≤ container, and each spacing step at least the one before.
// Only pairs the override touches are checked (a theme's own values are its business).
// The path named is the pair's first token when the override sets it, else the second.
func checkTokenOrder(override map[string]any, declared map[string]any) *globalStyleError {
	check := func(group string, pairs [][2]string, message string) *globalStyleError {
		overrideGroup, _ := override[group].(map[string]any)
		declaredGroup, _ := declared[group].(map[string]any)
		if len(overrideGroup) == 0 {
			return nil
		}
		for _, pair := range pairs {
			_, setA := overrideGroup[pair[0]]
			_, setB := overrideGroup[pair[1]]
			if !setA && !setB {
				continue
			}
			a, okA := mergedString(overrideGroup, declaredGroup, pair[0])
			b, okB := mergedString(overrideGroup, declaredGroup, pair[1])
			if !okA || !okB || lengthAtMost(a, b) {
				continue
			}
			key := pair[1]
			if setA {
				key = pair[0]
			}
			return &globalStyleError{Code: globalStyleTokenOrder, Path: group + "." + key, Message: fmt.Sprintf(message, pair[0], pair[1])}
		}
		return nil
	}
	if err := check("layout", [][2]string{{"contentWidth", "wideWidth"}, {"wideWidth", "container"}, {"contentWidth", "container"}}, "%s must be at most %s"); err != nil {
		return err
	}
	declaredSpacing, _ := declared["spacing"].(map[string]any)
	return check("spacing", spacingSteps(declaredSpacing), "spacing %s must be at most spacing %s")
}

// spacingSteps are the consecutive pairs of a numeric spacing scale (1, 2, … 10); a scale
// with any other key isn't ordered.
func spacingSteps(declared map[string]any) [][2]string {
	steps := make([]int, 0, len(declared))
	for key := range declared {
		n, err := strconv.Atoi(key)
		if err != nil || strconv.Itoa(n) != key {
			return nil
		}
		steps = append(steps, n)
	}
	sort.Ints(steps)
	pairs := make([][2]string, 0, len(steps))
	for i := 1; i < len(steps); i++ {
		pairs = append(pairs, [2]string{strconv.Itoa(steps[i-1]), strconv.Itoa(steps[i])})
	}
	return pairs
}

// ---- Groups (activity, release summaries; the styles screen's per-group reset, 9) ----

// globalStyleGroups name the parts of an override, in display order.
var globalStyleGroups = []struct {
	Name string
	Path []string
}{
	{"colors", []string{"colors"}},
	{"blockColors", []string{"blockColors"}},
	{"fonts", []string{"typography", "fontFamily"}},
	{"typeScale", []string{"typography", "fontSize"}},
	{"typeScale", []string{"typography", "lineHeight"}},
	{"layout", []string{"layout"}},
	{"spacing", []string{"spacing"}},
	{"radius", []string{"radius"}},
}

func styleSubtree(styles map[string]any, path []string) any {
	var current any = styles
	for _, key := range path {
		object, ok := current.(map[string]any)
		if !ok {
			return nil
		}
		current = object[key]
	}
	if object, ok := current.(map[string]any); ok && len(object) == 0 {
		return nil
	}
	return current
}

// changedGlobalStyleGroups names the groups whose values differ between two overrides:
// what an activity entry or a release records, never the values.
func changedGlobalStyleGroups(before, after map[string]any) []string {
	groups := []string{}
	seen := map[string]bool{}
	for _, group := range globalStyleGroups {
		if seen[group.Name] {
			continue
		}
		if !reflect.DeepEqual(styleSubtree(before, group.Path), styleSubtree(after, group.Path)) {
			groups = append(groups, group.Name)
			seen[group.Name] = true
		}
	}
	return groups
}

// decodeStoredStyles reads a stored override (always an object; '{}' by default) for
// comparison. Numbers decode as float64, as a normalized override holds them.
func decodeStoredStyles(raw json.RawMessage) map[string]any {
	styles := map[string]any{}
	if len(raw) > 0 {
		_ = json.Unmarshal(raw, &styles)
	}
	if styles == nil {
		styles = map[string]any{}
	}
	return styles
}

// canonicalStyles round-trips a normalized override through JSON, so it compares equal
// to one decoded from the database.
func canonicalStyles(styles map[string]any) (map[string]any, json.RawMessage, error) {
	encoded, err := json.Marshal(styles)
	if err != nil {
		return nil, nil, err
	}
	return decodeStoredStyles(encoded), encoded, nil
}

// ---- Contrast (6.3): a warning, never a refusal ----

const (
	contrastText = 4.5 // AA, normal text
	contrastUI   = 3.0 // AA, control edges and focus indicators
)

// contrastPair is [foreground, background, minimum], by the theme's colour names.
type contrastPair struct {
	Foreground string
	Background string
	Minimum    float64
}

// contrastPairs are the pairs the default theme's tokens.test.ts checks, which core's
// CONTRAST_PAIRS (web/src/lib/globalStyles.ts) also is; globalStyleVectors.json pins both.
// A pair naming a colour the theme doesn't declare is skipped.
var contrastPairs = []contrastPair{
	{"text", "background", contrastText},
	{"text", "surface", contrastText},
	{"text", "surface2", contrastText},
	{"text", "highlight", contrastText},
	{"textMuted", "background", contrastText},
	{"textMuted", "surface", contrastText},
	{"textMuted", "surface2", contrastText},
	{"secondary", "background", contrastText},
	{"secondary", "surface", contrastText},
	{"secondary", "surface2", contrastText},
	{"secondary", "primarySubtle", contrastText},
	{"primary", "background", contrastText},
	{"primary", "surface", contrastText},
	{"primaryHover", "background", contrastText},
	{"onPrimary", "primary", contrastText},
	{"onPrimary", "primaryHover", contrastText},
	{"borderStrong", "background", contrastUI},
	{"focus", "background", contrastUI},
	{"focus", "surface", contrastUI},
	{"text", "infoBg", contrastText},
	{"text", "successBg", contrastText},
	{"text", "warningBg", contrastText},
	{"text", "dangerBg", contrastText},
	{"primary", "infoBg", contrastText},
	{"primary", "successBg", contrastText},
	{"primary", "warningBg", contrastText},
	{"primary", "dangerBg", contrastText},
	{"info", "infoBg", contrastUI},
	{"success", "successBg", contrastUI},
	{"warning", "warningBg", contrastUI},
	{"danger", "dangerBg", contrastUI},
	{"borderStrong", "surface", contrastUI},
}

// blockColorSurfaces are the page surfaces tinted block text must read on.
var blockColorSurfaces = []string{"background", "surface", "surface2"}

// ContrastFailure is one pair below its minimum, in one palette. Block colours are named
// by path: blockColors.red.text on surface, or text on blockColors.red.background.
type ContrastFailure struct {
	Palette    string  `json:"palette"`
	Foreground string  `json:"foreground"`
	Background string  `json:"background"`
	Ratio      float64 `json:"ratio"`
	Minimum    float64 `json:"minimum"`
}

// ID is the pair's short name (light:text/surface), as the vectors and the web name it.
func (f ContrastFailure) ID() string {
	return f.Palette + ":" + f.Foreground + "/" + f.Background
}

func channel(hex string, i int) float64 {
	v, _ := strconv.ParseUint(hex[i:i+2], 16, 8)
	c := float64(v) / 255
	if c <= 0.04045 {
		return c / 12.92
	}
	return math.Pow((c+0.055)/1.055, 2.4)
}

func relativeLuminance(hex string) float64 {
	return 0.2126*channel(hex, 1) + 0.7152*channel(hex, 3) + 0.0722*channel(hex, 5)
}

// contrastRatio is WCAG 2's ratio of two #rrggbb colours.
func contrastRatio(a, b string) float64 {
	la, lb := relativeLuminance(a), relativeLuminance(b)
	if la < lb {
		la, lb = lb, la
	}
	return (la + 0.05) / (lb + 0.05)
}

func validColor(value any) (string, bool) {
	text, ok := value.(string)
	if !ok {
		return "", false
	}
	return normalizeColor(text)
}

// mergedPalette is the theme's palette with the override's colours.
func mergedPalette(declared, override map[string]any) map[string]string {
	palette := map[string]string{}
	for key, value := range declared {
		if color, ok := validColor(value); ok {
			palette[key] = color
		}
	}
	for key, value := range override {
		if _, declaredKey := palette[key]; !declaredKey {
			continue
		}
		if color, ok := validColor(value); ok {
			palette[key] = color
		}
	}
	return palette
}

func objectAt(root map[string]any, path ...string) map[string]any {
	current := root
	for _, key := range path {
		next, _ := current[key].(map[string]any)
		if next == nil {
			return map[string]any{}
		}
		current = next
	}
	return current
}

func roundRatio(r float64) float64 { return math.Round(r*100) / 100 }

// globalStyleContrast lists the pairs that fail with the override applied, light then
// dark, in CONTRAST_PAIRS order, then block colours by token name.
func globalStyleContrast(theme ThemeTokens, override map[string]any) []ContrastFailure {
	failures := []ContrastFailure{}
	for _, palette := range []string{"light", "dark"} {
		colors := mergedPalette(objectAt(theme.Tokens, "colors", palette), objectAt(override, "colors", palette))
		for _, pair := range contrastPairs {
			fg, okFg := colors[pair.Foreground]
			bg, okBg := colors[pair.Background]
			if !okFg || !okBg {
				continue
			}
			if ratio := contrastRatio(fg, bg); ratio < pair.Minimum {
				failures = append(failures, ContrastFailure{palette, pair.Foreground, pair.Background, roundRatio(ratio), pair.Minimum})
			}
		}
		declaredBlocks := objectAt(theme.Tokens, "blockColors", palette)
		overrideBlocks := objectAt(override, "blockColors", palette)
		for _, token := range sortedStyleKeys(declaredBlocks) {
			declaredToken, _ := declaredBlocks[token].(map[string]any)
			overrideToken, _ := overrideBlocks[token].(map[string]any)
			block := mergedPalette(declaredToken, overrideToken)
			if text, ok := block["text"]; ok {
				for _, surface := range blockColorSurfaces {
					bg, ok := colors[surface]
					if !ok {
						continue
					}
					if ratio := contrastRatio(text, bg); ratio < contrastText {
						failures = append(failures, ContrastFailure{palette, "blockColors." + token + ".text", surface, roundRatio(ratio), contrastText})
					}
				}
			}
			if fill, ok := block["background"]; ok {
				if text, ok := colors["text"]; ok {
					if ratio := contrastRatio(text, fill); ratio < contrastText {
						failures = append(failures, ContrastFailure{palette, "text", "blockColors." + token + ".background", roundRatio(ratio), contrastText})
					}
				}
			}
		}
	}
	return failures
}
