// The handful of line icons the UI components draw themselves (#338): 24px grid,
// currentColor, 1.75 stroke (2 at 14px and below), decorative. Screens keep using
// <Icon name="…"> until the redesign's icon set is chosen (see the design system's
// Iconography notes).

type IconProps = { size?: number } & Omit<SVGProps<SVGSVGElement>, "width" | "height">

function Svg({ size = 16, children, ...rest }: IconProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={size <= 14 ? 2 : 1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {children}
    </svg>
  )
}

